"""Build the synthetic Wii program and write it as C for the 3DS app and host tests.

The program is written here as PowerPC words, using the test encoders in tests/helpers.py.
It loops over four data words with lwzu and bdnz, runs a carry chain (addic, adde), a
multiply-high (mulhwu), and calls OSReport through HLE. The expected results are computed
here with plain Python integer arithmetic, not by running the interpreter.

Usage:
  python3 tools/make_synthetic.py [OUTPUT_DIR]

Writes OUTPUT_DIR/synthetic.c (default: platform/3ds/source/generated). The file defines
    int spm3ds_synthetic_run(void);
which runs the program on a fresh guest context and returns 1 when the results match.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from spm3ds.recomp import generate_c  # noqa: E402
from tests.helpers import (BLR, CODE_BASE, DATA_BASE, add, addi, addic, addis, bc, bl,  # noqa: E402
                           enc_xo, lwzu, mtctr, or_, program_image)

OSREPORT = 0x80004000          # HLE address; bound to hle_OSReport by name
FMT_OFFSET = 64                # format string location, relative to DATA_BASE
FMT = b"synthetic: r12=%08x\n\x00"
DATA_WORDS = [0x00000001, 0x80000000, 0x7FFFFFFF, 0x12345678]
M32 = 0xFFFFFFFF


def program():
    """The instruction words, in order. The comments give the index of each word."""
    words = [
        addi(3, 3, -4),                     # 0  r3 = DATA-4, so the first lwzu reads DATA+0
        addi(7, 0, 4),                      # 1  count
        mtctr(7),                           # 2  CTR = 4
        addi(6, 0, 0),                      # 3  sum = 0
        lwzu(5, 3, 4),                      # 4  loop: r5 = next word, r3 += 4
        add(6, 6, 5),                       # 5  sum += r5
        bc(16, 0, -8),                      # 6  bdnz back to word 4
        addi(10, 0, -1),                    # 7  r10 = 0xFFFFFFFF
        addic(11, 10, 1),                   # 8  r11 = 0, CA = 1
        enc_xo(31, 12, 6, 6, 0, 138),       # 9  adde r12 = sum + sum + CA = 2*sum + 1
        enc_xo(31, 13, 12, 12, 0, 11),      # 10 mulhwu r13 = high word of r12*r12
        addis(3, 0, DATA_BASE >> 16),       # 11 r3 = DATA
        addi(3, 3, FMT_OFFSET),             # 12 r3 = format string
        or_(4, 12, 12),                     # 13 r4 = r12, the OSReport argument
        bl(OSREPORT - (CODE_BASE + 14 * 4)),  # 14 OSReport(fmt, r12)
        or_(3, 6, 6),                       # 15 r3 = sum (HLE clears r3)
        BLR,                                # 16
    ]
    return words


def expected():
    """Expected r3 (sum) and r12 (2*sum + 1), from plain integer arithmetic."""
    total = sum(DATA_WORDS) & M32
    r12 = (2 * total + 1) & M32
    return total, r12


def data_init():
    body = b"".join(w.to_bytes(4, "big") for w in DATA_WORDS)
    body += bytes(FMT_OFFSET - len(body))
    body += FMT
    return body


def build_c():
    image = program_image(program(), CODE_BASE)
    source = generate_c(image, CODE_BASE, external_names={OSREPORT: "OSReport"})
    init = data_init()
    total, r12 = expected()
    lines = [
        "",
        "/* Entry point for the demo. Generated by tools/make_synthetic.py. */",
        "#include <stdio.h>",
        "#include <string.h>",
        "",
        f"static const uint8_t synthetic_init[{len(init)}] = {{",
        "    " + ", ".join(f"0x{b:02X}" for b in init),
        "};",
        "",
        "uint64_t spm3ds_synthetic_icount; /* instructions executed by the last run */",
        "int spm3ds_synthetic_quiet;       /* set to 1 to suppress the printed line (benchmarks) */",
        "",
        "int spm3ds_synthetic_run(void) {",
        "    static uint8_t mem[4096];",
        "    ppc_ctx c;",
        "    memset(&c, 0, sizeof c);",
        "    memcpy(mem, synthetic_init, sizeof synthetic_init);",
        f"    c.regions[0].base = 0x{DATA_BASE:08X}u;",
        "    c.regions[0].size = sizeof mem;",
        "    c.regions[0].data = mem;",
        "    c.nregions = 1;",
        f"    c.r[3] = 0x{DATA_BASE:08X}u;",
        f"    fn_{CODE_BASE:08X}(&c);",
        "    spm3ds_synthetic_icount = c.icount;",
        '    if (!spm3ds_synthetic_quiet) printf("synthetic: r3=%08x r12=%08x (expected %08x %08x)\\n", '
        "(unsigned)c.r[3], (unsigned)c.r[12], "
        f"{total:#010x}u, {r12:#010x}u);",
        f"    return c.r[3] == {total:#010x}u && c.r[12] == {r12:#010x}u;",
        "}",
        "",
    ]
    return source + "\n".join(lines)


def main(argv):
    out_dir = argv[1] if len(argv) > 1 else os.path.join(ROOT, "platform", "3ds", "source", "generated")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "synthetic.c")
    with open(path, "w", encoding="utf-8") as f:
        f.write(build_c())
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
