/* Hardware diagnostic screen (New 3DS / New 2DS XL).
 *
 * Shows: free application memory, whether the console is a New 3DS-class system, the ARM11
 * system tick rate used for timing, and a benchmark of the translated synthetic demo: executed
 * instructions per second, computed from the generated code's own instruction counter.
 *
 * UNCOMPILED ON HARDWARE. Names checked against libctru headers: osGetMemRegionFree
 * (3ds/os.h), cfguInit / CFGU_GetSystemModel / cfguExit (3ds/services/cfgu.h).
 */
#include <3ds.h>
#include <stdint.h>
#include <stdio.h>

extern uint64_t spm3ds_synthetic_icount; /* generated by tools/make_synthetic.py */
extern int spm3ds_synthetic_quiet;
int spm3ds_synthetic_run(void);

#define DIAG_RUNS 2000u

#ifndef SPM3DS_TICK_HZ
#  define SPM3DS_TICK_HZ 268123480ull /* see main.c: the tick rate is unverified */
#endif

/* CFG_MODEL_N3DS (2), CFG_MODEL_N3DSXL (4) and CFG_MODEL_N2DSXL (5) are New 3DS-class. */
static int is_new_class(void) {
    u8 model = 0xFF;
    if (R_FAILED(cfguInit())) return 0;
    Result rc = CFGU_GetSystemModel(&model);
    cfguExit();
    if (R_FAILED(rc)) return 0;
    return model == CFG_MODEL_N3DS || model == CFG_MODEL_N3DSXL || model == CFG_MODEL_N2DSXL;
}

void diag_screen(uint64_t (*now_ns)(void)) {
    uint32_t free_app = osGetMemRegionFree(MEMREGION_APPLICATION);
    int n3ds = is_new_class();
    uint64_t total_insns = 0;
    uint64_t t0, t1, elapsed;
    unsigned i, failures = 0;
    uint64_t ips;

    printf("\n== spm3ds hardware diagnostics ==\n");
    printf("Application memory free: %u KiB (%u bytes)\n",
           (unsigned)(free_app / 1024u), (unsigned)free_app);
    printf("New 3DS-class CPU and memory: %s\n", n3ds ? "yes" : "no (Old 3DS or 2DS)");
    printf("Tick rate used for timing: %llu Hz\n", (unsigned long long)SPM3DS_TICK_HZ);
#ifdef SPM3DS_NO_DIAG
    printf("Instruction counting: disabled at build time\n");
#else
    printf("Instruction counting: on\n");
#endif

    spm3ds_synthetic_quiet = 1;
    t0 = now_ns();
    for (i = 0; i < DIAG_RUNS; i++) {
        if (!spm3ds_synthetic_run()) failures++;
        total_insns += spm3ds_synthetic_icount;
    }
    t1 = now_ns();
    spm3ds_synthetic_quiet = 0;

    elapsed = t1 > t0 ? t1 - t0 : 1;
    /* total_insns * 1e9 stays below 2^64 for any realistic benchmark length. */
    ips = total_insns * 1000000000ull / elapsed;
    printf("Benchmark: %u runs of the translated demo\n", (unsigned)DIAG_RUNS);
    printf("Execution time: %llu us total, %llu ns per run\n",
           (unsigned long long)(elapsed / 1000u),
           (unsigned long long)(elapsed / DIAG_RUNS));
    printf("Translated instructions: %llu, per second: %llu\n",
           (unsigned long long)total_insns, (unsigned long long)ips);
    printf("Result check failures: %u\n", failures);
    printf("Press Y to return.\n");
}
