/* citro3d rendering backend for the spm3ds graphics demo (APP=gfx).
 *
 * Every citro3d and libctru name used here was checked against the public headers in the
 * devkitPro citro3d and libctru repositories (see docs/API_VERIFICATION.md). The build has NOT
 * been run on a device or with devkitARM in this environment.
 *
 * The cube is drawn with textured geometry: 36 vertices (12 triangles), position + texcoord,
 * one RGBA8 texture stored in PICA tiled layout (see tiling.c), a depth test, and a rotation
 * computed on the CPU. Culling is disabled, so triangle winding does not matter.
 * MIT License. */
#include <3ds.h>
#include <citro3d.h>
#include <stdlib.h>
#include <string.h>

#include "cube_shbin.h" /* generated by picasso + bin2s from cube.v.pica (see the Makefile) */
#include "gx_citro3d.h"
#include "tiling.h"

/* Transfer flags as used in citro3d's test program: RGBA8 in, RGB8 out, no scaling. */
#define DISPLAY_TRANSFER_FLAGS \
    (GX_TRANSFER_FLIP_VERT(0) | GX_TRANSFER_OUT_TILED(0) | GX_TRANSFER_RAW_COPY(0) | \
     GX_TRANSFER_IN_FORMAT(GX_TRANSFER_FMT_RGBA8) | GX_TRANSFER_OUT_FORMAT(GX_TRANSFER_FMT_RGB8) | \
     GX_TRANSFER_SCALING(GX_TRANSFER_SCALE_NO))

#define CLEAR_COLOR 0x68B0D8FFu  /* RGBA8 in the same byte order as citro3d's textured_cube */
#define TEX_SIZE 64u
#define CUBE_VERTS 36u

int gfx_init(void) {
    gfxInitDefault();
    C3D_Init(C3D_DEFAULT_CMDBUF_SIZE);
    return 0;
}

void gfx_shutdown(void) {
    C3D_Fini();
    gfxExit();
}

/* Builds the 36 vertices of a cube with side 1, centred on the origin. Each face is two
 * triangles; the texture covers each face once. */
static void build_cube(gfx_vertex *v) {
    unsigned n = 0;
    for (unsigned axis = 0; axis < 3; axis++) {
        for (int s = -1; s <= 1; s += 2) {
            unsigned ua = (axis + 1) % 3, va = (axis + 2) % 3;
            /* Corners of the face, in order, with matching texture coordinates. */
            static const float cu[4] = {-1.0f, 1.0f, 1.0f, -1.0f};
            static const float cv[4] = {-1.0f, -1.0f, 1.0f, 1.0f};
            static const float tu[4] = {0.0f, 1.0f, 1.0f, 0.0f};
            static const float tv[4] = {1.0f, 1.0f, 0.0f, 0.0f};
            static const unsigned idx[6] = {0, 1, 2, 0, 2, 3};
            for (unsigned k = 0; k < 6; k++) {
                unsigned c = idx[k];
                gfx_vertex *g = &v[n++];
                g->pos[axis] = 0.5f * (float)s;
                g->pos[ua] = 0.5f * cu[c];
                g->pos[va] = 0.5f * cv[c];
                g->tc[0] = tu[c];
                g->tc[1] = tv[c];
            }
        }
    }
}

int gfx_cube_create(gfx_cube *cube) {
    memset(cube, 0, sizeof *cube);

    cube->dvlb = DVLB_ParseFile((u32 *)cube_shbin, cube_shbin_size);
    if (!cube->dvlb) return -1;
    if (R_FAILED(shaderProgramInit(&cube->program))) return -2;
    if (R_FAILED(shaderProgramSetVsh(&cube->program, &cube->dvlb->DVLE[0]))) return -3;
    C3D_BindProgram(&cube->program);
    cube->u_projection = shaderInstanceGetUniformLocation(cube->program.vertexShader, "projection");
    cube->u_modelview = shaderInstanceGetUniformLocation(cube->program.vertexShader, "modelView");
    if (cube->u_projection < 0 || cube->u_modelview < 0) return -4;

    /* Texture: tiled RGBA8 generated on the host side of the program, copied into VRAM by
     * C3D_TexLoadImage (which copies bytes unchanged). */
    if (!C3D_TexInit(&cube->tex, TEX_SIZE, TEX_SIZE, GPU_RGBA8)) return -5;
    uint8_t *pixels = malloc(TEX_SIZE * TEX_SIZE * 4u);
    if (!pixels) return -6;
    tiling_fill_checker_rgba8(pixels, TEX_SIZE, TEX_SIZE);
    C3D_TexLoadImage(&cube->tex, pixels, GPU_TEXFACE_2D, 0);
    free(pixels);
    C3D_TexSetFilter(&cube->tex, GPU_LINEAR, GPU_NEAREST);

    /* Vertex buffer in linear memory: GPU-readable. */
    cube->vbo = linearAlloc(sizeof(gfx_vertex) * CUBE_VERTS);
    if (!cube->vbo) return -7;
    build_cube(cube->vbo);

    AttrInfo_Init(&cube->attr);
    AttrInfo_AddLoader(&cube->attr, 0, GPU_FLOAT, 3); /* inpos  = v0 */
    AttrInfo_AddLoader(&cube->attr, 1, GPU_FLOAT, 2); /* intex  = v1 */
    BufInfo_Init(&cube->buf);
    BufInfo_Add(&cube->buf, cube->vbo, sizeof(gfx_vertex), 2, 0x10);

    /* Top screen is 400 x 240 pixels; the target is created 240 wide, 400 tall as in examples. */
    cube->target = C3D_RenderTargetCreate(240, 400, GPU_RB_RGBA8, GPU_RB_DEPTH24_STENCIL8);
    if (!cube->target) return -8;
    C3D_RenderTargetSetOutput(cube->target, GFX_TOP, GFX_LEFT, DISPLAY_TRANSFER_FLAGS);

    /* Projection: 80 degree field of view, top-screen aspect ratio. */
    Mtx_PerspTilt(&cube->projection, C3D_AngleFromDegrees(80.0f), C3D_AspectRatioTop,
                  0.01f, 1000.0f, false);
    return 0;
}

void gfx_cube_frame(gfx_cube *cube, float angle_x, float angle_y) {
    C3D_Mtx modelview;
    Mtx_Identity(&modelview);
    Mtx_Translate(&modelview, 0.0f, 0.0f, -2.5f, true);
    Mtx_RotateX(&modelview, angle_x, true);
    Mtx_RotateY(&modelview, angle_y, true);

    /* State is set every frame because the translated-GX scene (gx_scene.c) shares the GPU. */
    C3D_BindProgram(&cube->program);
    C3D_SetAttrInfo(&cube->attr);
    C3D_SetBufInfo(&cube->buf);
    C3D_TexBind(0, &cube->tex);
    C3D_TexEnv *env = C3D_GetTexEnv(0);
    C3D_TexEnvInit(env);
    C3D_TexEnvSrc(env, C3D_Both, GPU_TEXTURE0, GPU_PRIMARY_COLOR, GPU_PRIMARY_COLOR);
    C3D_TexEnvFunc(env, C3D_Both, GPU_MODULATE);
    C3D_DepthTest(true, GPU_GREATER, GPU_WRITE_ALL);
    C3D_CullFace(GPU_CULL_NONE);

    C3D_FrameBegin(C3D_FRAME_SYNCDRAW);
    C3D_FrameDrawOn(cube->target);
    C3D_RenderTargetClear(cube->target, C3D_CLEAR_ALL, CLEAR_COLOR, 0);
    C3D_FVUnifMtx4x4(GPU_VERTEX_SHADER, cube->u_projection, &cube->projection);
    C3D_FVUnifMtx4x4(GPU_VERTEX_SHADER, cube->u_modelview, &modelview);
    C3D_DrawArrays(GPU_TRIANGLES, 0, CUBE_VERTS);
    C3D_FrameEnd(0);
}

void gfx_cube_destroy(gfx_cube *cube) {
    if (cube->target) C3D_RenderTargetDelete(cube->target);
    if (cube->vbo) linearFree(cube->vbo);
    C3D_TexDelete(&cube->tex);
    shaderProgramFree(&cube->program);
    if (cube->dvlb) DVLB_Free(cube->dvlb);
    memset(cube, 0, sizeof *cube);
}
